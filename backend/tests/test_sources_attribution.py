"""
/sources attribution (PARTITION D1b): the live list, the manifests, the
license texts, and the generated page data stay in step. No database.
"""
from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

BACKEND = Path(__file__).resolve().parent.parent
REPO = BACKEND.parent
MANIFESTS = BACKEND / "data" / "source_manifests"
GENERATOR = BACKEND / "scripts" / "attribution" / "build_sources.py"
GENERATED = REPO / "frontend" / "src" / "data" / "sources.generated.json"

EXCLUDED = ("icewordnet", "latin-wordnet", "ruwordnet")
WORDNET_STYLE = ("omw-cmn", "omw-he", "omw-ja", "omw-pl")
REQUIRED = ("source_slug", "name", "source_type", "license", "attribution",
            "language_code")


def live_slugs() -> list[str]:
    return [ln.strip() for ln in (MANIFESTS / "live_sources.txt").read_text().splitlines()
            if ln.strip() and not ln.lstrip().startswith("#")]


def generated() -> dict:
    return json.loads(GENERATED.read_text(encoding="utf-8"))


def test_live_list_is_sorted_and_unique():
    slugs = live_slugs()
    assert slugs == sorted(set(slugs))
    assert len(slugs) == 13


def test_every_live_slug_has_a_manifest():
    for slug in live_slugs():
        assert (MANIFESTS / slug / "source_manifest.json").is_file(), slug


def test_excluded_sources_are_not_live():
    data = generated()
    for slug in EXCLUDED:
        assert slug not in live_slugs()
        assert slug not in {s["slug"] for s in data["sources"]}
        assert slug not in {t["id"] for t in data["licenseTexts"]}


def test_generated_sources_equal_live_slugs():
    assert sorted(s["slug"] for s in generated()["sources"]) == live_slugs()


def test_generated_json_is_current():
    r = subprocess.run([sys.executable, str(GENERATOR), "--check"],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr


def test_required_fields_present():
    for slug in live_slugs():
        m = json.loads((MANIFESTS / slug / "source_manifest.json").read_text())
        for field in REQUIRED:
            assert m.get(field), f"{slug}: {field}"
        assert m["source_slug"] == slug
        assert m.get("license_url") or slug in WORDNET_STYLE, slug


def test_wordnet_style_sources_carry_their_license_text():
    index = json.loads((MANIFESTS / "_licenses" / "licenses.json").read_text())
    texts = {t["id"]: t for t in generated()["licenseTexts"]}
    by_slug = {s["slug"]: s for s in generated()["sources"]}
    for slug in [*WORDNET_STYLE, "omw-el"]:
        entry = index[slug]
        data = (MANIFESTS / "_licenses" / entry["file"]).read_bytes()
        assert data.strip(), slug
        assert hashlib.sha256(data).hexdigest() == entry["sha256"], slug
        assert by_slug[slug]["licenseTextId"] == slug
        assert texts[slug]["text"] == data.decode("utf-8")
    pl = (MANIFESTS / "_licenses" / index["omw-pl"]["file"]).read_text()
    assert "WordNet 3.0 Copyright 2006 by Princeton" in pl   # Princeton text, once


def test_machine_generated_source_is_labelled():
    llm = next(s for s in generated()["sources"] if s["slug"] == "llm-root")
    assert llm["section"] == "machine"
    assert "machine-generated by Google Gemini" in llm["attribution"]


def test_generator_fails_on_missing_manifest(tmp_path):
    copy = tmp_path / "source_manifests"
    shutil.copytree(MANIFESTS, copy)
    shutil.rmtree(copy / "kaikki")
    r = subprocess.run([sys.executable, str(GENERATOR), "--manifests", str(copy),
                        "--out", str(tmp_path / "out.json")],
                       capture_output=True, text=True)
    assert r.returncode == 2
    assert "kaikki" in r.stderr and "no manifest" in r.stderr
    assert not (tmp_path / "out.json").exists()


@pytest.mark.parametrize("slug", EXCLUDED)
def test_generator_refuses_an_excluded_slug(tmp_path, slug):
    copy = tmp_path / "source_manifests"
    shutil.copytree(MANIFESTS, copy)
    with (copy / "live_sources.txt").open("a") as f:
        f.write(f"{slug}\n")
    r = subprocess.run([sys.executable, str(GENERATOR), "--manifests", str(copy),
                        "--out", str(tmp_path / "out.json")],
                       capture_output=True, text=True)
    assert r.returncode == 2 and "excluded" in r.stderr
