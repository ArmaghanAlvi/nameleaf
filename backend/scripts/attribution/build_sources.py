"""
Generate the /sources page data from the source manifests (PARTITION D1b).

Reads backend/data/source_manifests/:
  live_sources.txt                 the live slugs (master's `sources` table)
  <slug>/source_manifest.json      one manifest per live slug
  _licenses/licenses.json + files  license texts reproduced verbatim
  _models/*.json                   models credited on the page

Writes frontend/src/data/sources.generated.json, deterministically (sorted
keys, stable order, trailing newline). The frontend image is built from
./frontend only, so the page reads this committed file, never backend/.

Standard library only. Every string on the page that names a license,
attribution or citation comes from these files; nothing is written here.

Usage (from the repo root):
  python backend/scripts/attribution/build_sources.py          # write
  python backend/scripts/attribution/build_sources.py --check  # exit 1 if stale
"""
from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
MANIFESTS = REPO / "backend" / "data" / "source_manifests"
OUT = REPO / "frontend" / "src" / "data" / "sources.generated.json"

# Manifests exist for these, but they have no database rows (A-0.9) and must
# never appear on the page or in the live list.
EXCLUDED = ("icewordnet", "latin-wordnet", "ruwordnet")

REQUIRED = ("source_slug", "name", "source_type", "license", "attribution",
            "language_code")

SECTIONS = {"dictionary_dump": "dictionary", "wordnet": "wordnet", "llm": "machine"}
SECTION_ORDER = ("dictionary", "wordnet", "machine")

GENERATED_NOTE = ("Generated by backend/scripts/attribution/build_sources.py "
                  "from backend/data/source_manifests. Do not edit.")


class BuildError(Exception):
    pass


def read_live(manifests: Path) -> list[str]:
    path = manifests / "live_sources.txt"
    if not path.is_file():
        raise BuildError(f"missing {path}")
    slugs = [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines()
             if ln.strip() and not ln.lstrip().startswith("#")]
    if len(set(slugs)) != len(slugs):
        raise BuildError("live_sources.txt lists a slug twice")
    bad = sorted(set(slugs) & set(EXCLUDED))
    if bad:
        raise BuildError(f"excluded source(s) in live_sources.txt: {', '.join(bad)}")
    return sorted(slugs)


def read_license_texts(manifests: Path) -> dict[str, dict]:
    index_path = manifests / "_licenses" / "licenses.json"
    if not index_path.is_file():
        return {}
    index = json.loads(index_path.read_text(encoding="utf-8"))
    texts: dict[str, dict] = {}
    for slug, entry in index.items():
        if slug.startswith("_"):
            continue
        path = manifests / "_licenses" / entry["file"]
        data = path.read_bytes()
        if not data.strip():
            raise BuildError(f"license text {path.name} is empty")
        digest = hashlib.sha256(data).hexdigest()
        if digest != entry["sha256"]:
            raise BuildError(f"license text {path.name}: sha256 {digest}, "
                             f"licenses.json records {entry['sha256']}")
        texts[slug] = {"id": slug, "appliesTo": slug,
                       "text": data.decode("utf-8")}
    return texts


def read_source(manifests: Path, slug: str, license_texts: dict) -> dict:
    path = manifests / slug / "source_manifest.json"
    if not path.is_file():
        raise BuildError(f"live source {slug!r} has no manifest ({path})")
    m = json.loads(path.read_text(encoding="utf-8"))
    missing = [f for f in REQUIRED if not m.get(f)]
    if missing:
        raise BuildError(f"{slug}: manifest lacks {', '.join(missing)}")
    if m["source_slug"] != slug:
        raise BuildError(f"{slug}: manifest source_slug is {m['source_slug']!r}")
    section = SECTIONS.get(m["source_type"])
    if section is None:
        raise BuildError(f"{slug}: unknown source_type {m['source_type']!r}")
    if not m.get("license_url") and slug not in license_texts:
        raise BuildError(f"{slug}: no license_url and no license text")
    if m.get("language_codes"):
        codes = sorted(m["language_codes"])
    elif m["language_code"] != "mul":
        codes = [m["language_code"]]
    else:
        codes = []
    return {
        "slug": slug,
        "section": section,
        "name": m["name"],
        "homepage": m.get("source_homepage"),
        "upstream": m.get("upstream"),
        "upstreamUrl": m.get("upstream_url"),
        "languageCodes": codes,
        "attribution": m["attribution"],
        "license": m["license"],
        "licenseUrl": m.get("license_url"),
        "licenseTextId": slug if slug in license_texts else None,
    }


def read_models(manifests: Path) -> list[dict]:
    models = []
    for path in sorted((manifests / "_models").glob("*.json")):
        m = json.loads(path.read_text(encoding="utf-8"))
        for f in ("name", "revision", "license", "citation"):
            if not m.get(f):
                raise BuildError(f"{path.name}: lacks {f}")
        models.append({f: m[f] for f in ("name", "revision", "license", "citation")})
    return models


def build(manifests: Path = MANIFESTS) -> str:
    live = read_live(manifests)
    license_texts = read_license_texts(manifests)
    unused = sorted(set(license_texts) - set(live))
    if unused:
        raise BuildError(f"license text(s) for non-live source(s): {', '.join(unused)}")
    sources = [read_source(manifests, slug, license_texts) for slug in live]
    sources.sort(key=lambda s: (SECTION_ORDER.index(s["section"]), s["slug"]))
    data = {
        "_generated": GENERATED_NOTE,
        "sources": sources,
        "licenseTexts": [license_texts[k] for k in sorted(license_texts)],
        "models": read_models(manifests),
    }
    return json.dumps(data, sort_keys=True, ensure_ascii=False, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed file differs from a fresh build")
    ap.add_argument("--manifests", type=Path, default=MANIFESTS)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    try:
        fresh = build(args.manifests)
    except BuildError as e:
        print(f"build_sources: {e}", file=sys.stderr)
        return 2
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.is_file() else ""
        if current == fresh:
            print(f"build_sources: {args.out.name} is current")
            return 0
        diff = difflib.unified_diff(current.splitlines(), fresh.splitlines(),
                                    "committed", "fresh", lineterm="", n=1)
        print(f"build_sources: {args.out.name} is STALE; run "
              "backend/scripts/attribution/build_sources.py", file=sys.stderr)
        print("\n".join(list(diff)[:40]), file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(fresh, encoding="utf-8")
    print(f"build_sources: wrote {args.out} ({fresh.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
